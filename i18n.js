/* Santa multilingual runtime: languages are device-local, offline, and independent of test mode. */
(() => {
  'use strict';
  const choices = new Set(['en','da','sv']);
  let lang = 'en';
  try { const stored = localStorage.getItem('santa-language-2026'); if (choices.has(stored)) lang = stored; }
  catch (_) {}
  const source = window.SantaContent;
  const pack = lang === 'da' ? window.SantaLocaleDA : lang === 'sv' ? window.SantaLocaleSV : null;
  const escape = text => String(text).replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
  const ui = new Map((window.SantaUIText || []).map(([en,da,sv]) => [en,lang === 'da' ? da : lang === 'sv' ? sv : en]));
  const tr = text => ui.get(String(text)) || String(text);
  const month = lang === 'da' ? 'DEC' : lang === 'sv' ? 'DEC' : 'DEC';
  const phrase = (en,da,sv) => lang === 'da' ? da : lang === 'sv' ? sv : en;
  if (pack && Array.isArray(pack.missions) && pack.missions.length === 12 && Array.isArray(pack.rules) && pack.rules.length === 7) {
    source.story = pack.story;
    for (let i = 0; i < 12; i++) {
      const entry = pack.missions[i], mission = source.missions[i];
      mission.title = entry.title;
      mission.skill = entry.skill;
      mission.message = entry.message;
      mission.bonus = entry.bonus;
      mission.help = entry.help;
      mission.assignment = '<p>' + escape(entry.intro) + '</p><p>' + phrase('Requirements:','Krav:','Krav:') + '</p><ol>' + entry.requirements.map(item => '<li>' + escape(item) + '</li>').join('') + '</ol>' + (entry.extra ? '<p>' + escape(entry.extra) + '</p>' : '');
    }
    source.rules = pack.rules.map(([title, paragraphs]) => ({
      title,body:paragraphs.map(p => '<p>' + escape(p).replace(/\\.html/g,'.html') + '</p>').join('')
    }));
  }
  document.documentElement.lang = lang;
  document.documentElement.dataset.language = lang;
  const dynamicTranslate = text => {
    const direct = tr(text);
    if (direct !== text) return direct;
    let match;
    if ((match = /^MISSION (\d+) \/ 12 · DECEMBER (\d+)$/.exec(text))) return phrase(text, 'MISSION '+match[1]+' / 12 · '+match[2]+'. DECEMBER', 'UPPDRAG '+match[1]+' / 12 · '+match[2]+' DECEMBER');
    if ((match = /^MISSION (\d+) · DECEMBER (\d+)$/.exec(text))) return phrase(text, 'MISSION '+match[1]+' · '+match[2]+'. DECEMBER', 'UPPDRAG '+match[1]+' · '+match[2]+' DECEMBER');
    if ((match = /^DEC (\d+)$/.exec(text))) return text; // Date labels intentionally concise in all languages
    if ((match = /^(\d+) KB · Saved on this device$/.exec(text))) return match[1]+' KB · '+phrase('Saved on this device','Gemt på denne enhed','Sparat på den här enheten');
    // Parameterized strings generated by app.js; keep names and filenames untouched.
    if ((match = /^Mission (\d+), December (\d+)\. (.+)$/.exec(text))) {
      const [, number, day, status] = match;
      const date = phrase('December ' + day,day + '. december',day + ' december');
      if (status.startsWith('Locked. Opens December ')) return phrase(text,
        'Mission ' + number + ', ' + date + '. Låst. Åbner ' + day + '. december 2026.',
        'Uppdrag ' + number + ', ' + date + '. Låst. Öppnas ' + day + ' december 2026.');
      const states = {
        'Completed. Open mission.':['Fuldført. Åbn missionen.','Slutfört. Öppna uppdraget.'],
        'New mission available. Open mission.':['Ny mission er klar. Åbn missionen.','Nytt uppdrag finns. Öppna uppdraget.'],
        'Available. Open mission.':['Klar. Åbn missionen.','Tillgängligt. Öppna uppdraget.']
      };
      if (states[status]) return phrase(text,'Mission ' + number + ', ' + date + '. ' + states[status][0],
        'Uppdrag ' + number + ', ' + date + '. ' + states[status][1]);
    }
    if ((match = /^Agent (.+), all 12 missions complete! Santa awards you the Golden Inventor Star\. Kevin would like to be your assistant\.$/.exec(text)))
      return phrase(text,'Agent ' + match[1] + ', alle 12 missioner er fuldført! Julemanden giver dig den gyldne opfinderstjerne. Kevin vil gerne være din assistent.',
        'Agent ' + match[1] + ', alla 12 uppdrag är klara! Tomten ger dig den gyllene uppfinnarstjärnan. Kevin vill gärna vara din assistent.');
    if ((match = /^✦ Santa left you (\d+) secret missions to discover\.$/.exec(text)))
      return phrase(text,'✦ Julemanden har efterladt ' + match[1] + ' hemmelige missioner til dig.',
        '✦ Tomten har lämnat ' + match[1] + ' hemliga uppdrag åt dig.');
    if ((match = /^Santa says: “Brilliant work, Agent (.+)! Kevin has only exploded one biscuit today\.”$/.exec(text)))
      return phrase(text,'Julemanden siger: »Flot arbejde, agent ' + match[1] + '! Kevin har kun sprængt én småkage i luften i dag.«',
        'Tomten säger: ”Bra jobbat, agent ' + match[1] + '! Kevin har bara sprängt en kaka idag.”');
    if ((match = /^Santa says: “Another disaster defeated, Agent (.+)! Cookie department: issue a victory biscuit\.”$/.exec(text)))
      return phrase(text,'Julemanden siger: »Endnu en katastrofe afværget, agent ' + match[1] + '! Småkageafdelingen: udlever en sejrssmåkage.«',
        'Tomten säger: ”Ännu en katastrof avvärjd, agent ' + match[1] + '! Kakavdelningen: dela ut en segerkaka.”');
    if ((match = /^Agent (.+) — your North Pole badge is ready!$/.exec(text)))
      return phrase(text,'Agent ' + match[1] + ' — dit Nordpolsmærke er klar!',
        'Agent ' + match[1] + ' — ditt Nordpolsmärke är klart!');
    if ((match = /^Delete “(.+)” from this app on this device\?$/.exec(text)))
      return phrase(text,'Vil du slette »' + match[1] + '« fra appen på denne enhed?',
        'Vill du ta bort ”' + match[1] + '” från appen på den här enheten?');
    if ((match = /^Shhh… Santa is still sealing this envelope! Mission (\d+) opens December (\d+), 2026 at midnight on this device\.$/.exec(text)))
      return phrase(text,'Shhh… Julemanden er stadig ved at forsegle brevet! Mission ' + match[1] + ' åbner den ' + match[2] + '. december 2026 ved midnat på denne enhed.',
        'Schhh… Tomten förseglar fortfarande brevet! Uppdrag ' + match[1] + ' öppnas den ' + match[2] + ' december 2026 vid midnatt på den här enheten.');
    if ((match = /^Interactive preview of (.+)$/.exec(text)))
      return phrase(text,'Interaktiv forhåndsvisning af ' + match[1], 'Interaktiv förhandsvisning av ' + match[1]);
    return text;
  };
  function translateAttributes(element) {
    if (lang === 'en' || element.nodeType !== Node.ELEMENT_NODE) return;
    if (element.matches('script,style,svg,textarea,pre,code')) return;
    for (const attr of ['aria-label','placeholder']) {
      const original = element.getAttribute(attr);
      if (!original) continue;
      const localized = dynamicTranslate(original);
      if (original !== localized) element.setAttribute(attr,localized);
    }
  }
  function translateNode(node) {
    if (lang === 'en') return;
    if (node.nodeType === Node.TEXT_NODE) {
      const parent = node.parentElement;
      if (!parent || parent.closest('script,style,svg,textarea,pre,code,#agent-name,#intro-story,#santa-message,#hint-text,#rescue-text,#creation-filename,#name-input')) return;
      const raw = node.nodeValue || '', trimmed = raw.trim();
      if (!trimmed) return;
      const next = dynamicTranslate(trimmed);
      if (trimmed !== next) node.nodeValue = raw.replace(trimmed,next);
      return;
    }
    if (node.nodeType !== Node.ELEMENT_NODE && node.nodeType !== Node.DOCUMENT_NODE) return;
    if (node.nodeType === Node.ELEMENT_NODE && node.matches('script,style,svg,textarea,pre,code')) return;
    if (node.nodeType === Node.ELEMENT_NODE) translateAttributes(node);
    // Attributes are not part of TreeWalker's text-node view.
    if (node.querySelectorAll) node.querySelectorAll('[aria-label],[placeholder]').forEach(translateAttributes);
    const walker = document.createTreeWalker(node, NodeFilter.SHOW_TEXT);
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach(translateNode);
  }
  translateNode(document);
  const observer = new MutationObserver(changes => {
    if (lang === 'en') return;
    for (const change of changes) {
      if (change.type === 'characterData') translateNode(change.target);
      else if (change.type === 'attributes') translateAttributes(change.target);
      else change.addedNodes.forEach(translateNode);
    }
  });
  observer.observe(document.documentElement,{subtree:true,childList:true,characterData:true,attributes:true,attributeFilter:['aria-label','placeholder']});
  document.querySelectorAll('[data-lang]').forEach(button => {
    const code = button.dataset.lang;
    button.setAttribute('aria-pressed',String(code === lang));
    button.addEventListener('click', () => {
      if (!choices.has(code) || code === lang) return;
      try { localStorage.setItem('santa-language-2026',code); }
      catch (_) { /* This browser cannot remember the preference. */ }
      location.reload();
    });
  });
  window.SantaI18n = Object.freeze({lang,tr,phrase,translateNode});
})();
